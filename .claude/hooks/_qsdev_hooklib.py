def wrapper_name(token: str) -> str:
    """The name a command word is looked up by in WRAPPERS: its basename,
    lower-cased (macOS and Windows file systems are case-insensitive), with a
    Windows .exe suffix removed."""
    name = os.path.basename(token.replace("\\", "/")).lower()
    return name[:-4] if name.endswith(".exe") else name


def _short_cluster(flag: str, spec: WrapperSpec, name: str) -> tuple:
    """Split a short-option token for a wrapper into (option, eq, inline value).
    A cluster (`-Eu`, `-iS`, `-qc`, `-n10`) is read letter by letter up to the
    first option that takes a value, stops execution or sends a command; the
    rest of the token is that option's inline value. An option that may
    create (screen -R) wins over the rest of its cluster, and one whose value
    is optional ends the cluster (`-dR s` and `-xRR s` take the session name
    s). Returns ("", "", "") for a cluster of booleans. Short options take no
    `=`: `-S'A=1 npm i'` keeps its `=`."""
    takes_value = spec.value | spec.script | ({"-S"} if name == "env" else set())
    if flag in takes_value or flag in spec.no_exec or flag in spec.command or len(flag) <= 2:
        return flag, "", ""
    for k in range(1, len(flag)):
        if "-" + flag[k] in spec.creates:
            return "-" + flag[k], "", ""
    for k in range(1, len(flag)):
        opt = "-" + flag[k]
        if opt in spec.no_exec or opt in spec.command or opt in spec.optional:
            return opt, "", ""
        if opt in takes_value:
            inline = flag[k + 1:]
            return opt, ("=" if inline else ""), inline
    return "", "", ""


class WrapperStep(NamedTuple):
    end: int                 # index just past the wrapper, its options and positional
    scripts: tuple           # the wrapper's own shell scripts (flock -c, watch, tmux new)
    no_exec: bool            # the wrapper runs no command (command -v, screen -r)
    split: Optional[str]     # env -S string: split it into the command that follows `end`


class _Options(NamedTuple):
    j: int                   # index of the first operand
    scripts: tuple           # script option values seen (flock -c)
    no_exec: bool
    split: Optional[str]
    command: bool            # argv[j] is a command for a running instance (screen -X)
    # When a creating option ran (screen -R), the index of the word an
    # optional value took as a session name, else -1. Whether screen takes it
    # as the name or as the command is not certain, so both are judged.
    maybe_command: int = -1


def _skip_options(argv: list, j: int, spec: WrapperSpec, name: str, scripts: tuple = ()) -> _Options:
    """Skip a wrapper's options from argv[j]: what they said, and the index of
    the first operand."""
    n = len(argv)
    no_exec = creates = False
    taken = -1  # index of the first word an optional value took
    while j < n and argv[j].startswith("-") and argv[j] != "-":
        flag = argv[j]
        j += 1
        if flag == "--":
            break
        if flag.startswith("--"):
            base, eq, inline = flag.partition("=")
        else:
            base, eq, inline = _short_cluster(flag, spec, name)
            if not base:
                continue  # a cluster of boolean flags (`-Ei`)
        if base in spec.command:
            return _Options(j, scripts, False, None, True)
        if base in spec.optional and not eq and j < n and not argv[j].startswith("-"):
            taken = j if taken < 0 else taken
            j += 1
        creates = creates or base in spec.creates
        if base in spec.no_exec:
            no_exec = True  # unless a later option sends a command (screen -x s -X exec)
            continue
        if name == "env" and base in ("--split-string", "-S"):
            # env -S 'npm install x': the string is split into the command.
            if not eq:
                inline = argv[j] if j < n else ""
                j += 1
            return _Options(j, scripts, False, inline, False)
        if base in spec.script:
            if not eq:
                inline = argv[j] if j < n else ""
                j += 1
            scripts += (inline,)
            continue
        if not eq and base in spec.value and j < n:
            j += 1
    return _Options(j, scripts, no_exec and not creates, None, False, taken if creates else -1)


# screen's `exec [[fdpat] cmd]` file-descriptor pattern (`.!.`, `!..|`).
_SCREEN_FDPAT_RE = re.compile(r"^[.!:|]+$")


def _screen_command(argv: list, j: int, scripts: tuple) -> WrapperStep:
    """A command sent to a running screen session (`screen -X CMD ARGS`):
    `exec` and `screen` run their operands as a program, `stuff` types its
    text into the session's shell. Any other screen command is left as the
    command (end = j), so callers still judge its words."""
    n = len(argv)
    cmd = argv[j] if j < n else ""
    if cmd == "exec":
        k = j + 1
        if k < n and _SCREEN_FDPAT_RE.match(argv[k]):
            k += 1
        return WrapperStep(k, scripts, False, None)
    if cmd == "screen":
        opts = _skip_options(argv, j + 1, WRAPPERS["screen"], "screen", scripts)
        return WrapperStep(opts.j, opts.scripts, opts.no_exec, None)
    if cmd == "stuff":
        text = " ".join(argv[j + 1:]).replace("\\n", "\n").replace("\\r", "\n")
        return WrapperStep(n, scripts + (text,), False, None)
    return WrapperStep(j, scripts, False, None)


def _tmux_commands(argv: list) -> list:
    """Split tmux's argv into its `;`-separated commands. A word `;` separates;
    a word ending in an unescaped `;` ends a command; `\\;` is a literal."""
    cmds: list = [[]]
    for word in argv:
        if word == ";":
            cmds.append([])
        elif word.endswith("\\;"):
            cmds[-1].append(word[:-2] + ";")
        elif word.endswith(";"):
            cmds[-1].append(word[:-1])
            cmds.append([])
        else:
            cmds[-1].append(word)
    return [c for c in cmds if c]


def _tmux_subcommand(spec: WrapperSpec, word: str) -> Optional[WrapperSpec]:
    """The grammar of the subcommand word names: an exact name or alias, else
    a mapped full name it is a prefix of. tmux accepts a unique prefix; an
    ambiguous one runs nothing, so taking any match only over-reports."""
    if word in spec.subcommands:
        return spec.subcommands[word]
    for full, sub in spec.subcommands.items():
        if "-" in full and full.startswith(word):
            return sub
    return None


def _tmux_lines(lines: list, out: list) -> None:
    """Follow each of lines as a tmux command line, appending its scripts."""
    for line in lines:
        try:
            words = shlex.split(line)
        except ValueError:  # unbalanced quotes: judge the line as a script
            out.append(line)
            continue
        out.extend(skip_wrapper(["tmux"] + words, 0, "tmux").scripts)


def _skip_tmux(argv: list, j: int, spec: WrapperSpec, scripts: tuple) -> WrapperStep:
    """tmux runs no program itself: every command it is given is returned as
    a script. A command that starts a shell or types keys into one yields
    that shell's script; an if-shell/confirm-before operand that is a tmux
    command line is followed in turn. Any other command (set
    default-command, bind, set-hook, command-prompt ...) yields its own
    words as a command line and each operand followed as a tmux command
    line, so a quoted shell command among them (`bind x run-shell 'rm -rf
    ~'`) is judged too. That over-reports rather than hides a command."""
    out = list(scripts)
    for cmd in _tmux_commands(argv[j:]):
        sub = _tmux_subcommand(spec, cmd[0])
        if sub is None:
            out.append(" ".join(cmd))
            _tmux_lines(cmd[1:], out)
            continue
        opts = _skip_options(cmd, 1, sub, "tmux")
        out.extend(opts.scripts)
        operands = cmd[opts.j:]
        if sub.joins:
            out.append(" ".join(operands))
            continue
        if sub.commands == "rest" and operands:
            out.append(operands[0])
            operands = operands[1:]
        _tmux_lines(operands, out)
    return WrapperStep(len(argv), tuple(s for s in out if s.strip()), False, None)


def skip_wrapper(argv: list, i: int, name: str) -> WrapperStep:
    """Skip the wrapper argv[i] (WRAPPERS[name]) with its options, positional
    and subcommand, so argv[end] is the next command word."""
    spec = WRAPPERS[name]
    n = len(argv)
    opts = _skip_options(argv, i + 1, spec, name)
    if opts.command:
        return _screen_command(argv, opts.j, opts.scripts)
    if opts.no_exec or opts.split is not None:
        return WrapperStep(opts.j, opts.scripts, opts.no_exec, opts.split)
    if opts.maybe_command >= 0:  # `screen -R s CMD`: s may be the command too
        return WrapperStep(opts.j, opts.scripts + (shlex.join(argv[opts.maybe_command:]),), False, None)
    if spec.subcommands is not None:
        return _skip_tmux(argv, opts.j, spec, opts.scripts)
    j, scripts = opts.j, opts.scripts
    if spec.joins:
        return WrapperStep(n, scripts + (" ".join(argv[j:]),), False, None)  # `watch 'rm x'` runs `sh -c`
    # The positional is exactly one word, whatever it looks like: timeout's
    # DURATION may be `.5`, `+5`, `inf`, `infinity` or ` 5`, not only digits.
    if spec.positional and j < n and not argv[j].startswith("-"):
        # Options may follow the positional (`flock FILE -c CMD`,
        # `script FILE -q -c CMD`): GNU getopt permutes.
        opts = _skip_options(argv, j + 1, spec, name, scripts)
        if opts.no_exec or opts.split is not None:
            return WrapperStep(opts.j, opts.scripts, opts.no_exec, opts.split)
        j, scripts = opts.j, opts.scripts
    if scripts:
        return WrapperStep(n, scripts, False, None)  # flock/script -c: the script is the command
    return WrapperStep(j, scripts, False, None)


_ASSIGNMENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*=")


def unwrap(argv: list) -> tuple:
    """Strip leading VAR=value assignments and exec wrappers from a plain
    argv. Returns (inner argv, scripts): the command that really runs (empty
    when a wrapper runs none) and the shell scripts the wrappers run
    themselves, which the caller parses as command lines too."""
    scripts: list = []
    i = 0
    while i < len(argv):
        if _ASSIGNMENT_RE.match(argv[i]):
            i += 1
            continue
        name = wrapper_name(argv[i])
        if name not in WRAPPERS:
            break
        step = skip_wrapper(argv, i, name)
        scripts.extend(step.scripts)
        if step.no_exec:
            return [], scripts
        if step.split is not None:
            try:
                head = shlex.split(step.split)
            except ValueError:  # unbalanced quotes: split what is there
                head = re.sub(r"[\"']", " ", step.split).split()
            argv, i = head + argv[step.end:], 0
            continue
        i = step.end
    return argv[i:], scripts
