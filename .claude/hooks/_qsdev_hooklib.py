"""
Shared library for qsdev's Python hooks (generated by qsdev; do not edit).

Not a hook: nothing registers it in settings.json. Each hook loads it by its
explicit file path (never through sys.path, which the hooks scrub so a module
planted beside them cannot replace the stdlib) and blocks, exit 2, when it is
missing or broken.

Provides the interpreter floor, the evaluation deadline watchdog, private
append-only files, the shared hook audit log and the one table of exec
wrappers (sudo, env, flock, tmux ...) every hook follows to the command a
wrapped command line really runs.

Plain Python 3.9: no `from __future__` imports and no subscripted builtins in
evaluated annotations, so an older interpreter still reaches the version check
and blocks instead of crashing with a non-blocking exit 1.
"""

import sys

# Oldest interpreter the hooks support (Go: types.MinHookPython). Below it,
# block (exit 2) instead of crashing with exit 1, which Claude Code treats as
# a non-blocking error. SystemExit is not an Exception, so it passes through
# the hooks' library-load guard.
MIN_PYTHON = (3, 9)
if sys.version_info < MIN_PYTHON:
    print(f"qsdev hooks require Python {'.'.join(map(str, MIN_PYTHON))}+ "
          f"(found {sys.version.split()[0]}); blocking to fail closed.", file=sys.stderr)
    sys.exit(2)

import json  # noqa: E402
import os  # noqa: E402
import re  # noqa: E402
import shlex  # noqa: E402
import threading  # noqa: E402
from datetime import datetime, timezone  # noqa: E402
from typing import NamedTuple, Optional  # noqa: E402

try:
    import fcntl  # noqa: E402
except ImportError:  # Windows
    fcntl = None
try:
    import msvcrt  # noqa: E402
except ImportError:  # POSIX
    msvcrt = None


# ---------------------------------------------------------------------------
# Deadline
# ---------------------------------------------------------------------------

def deadline_seconds(seconds: float) -> float:
    """The effective deadline: seconds, or QSDEV_HOOK_DEADLINE_MS when that is
    shorter. The variable can only shorten the deadline."""
    try:
        return min(float(seconds), int(os.environ.get("QSDEV_HOOK_DEADLINE_MS", "")) / 1000)
    except ValueError:
        return float(seconds)


def arm_deadline(hook: str, seconds: float) -> None:
    """Start a daemon watchdog that blocks (exit 2) once the deadline passes.

    A hook's deadline is its registered settings.json timeout minus 2s: Claude
    Code lets the tool call through when a hook times out, so the watchdog
    blocks first. Known limit: a C-level regex match that holds the GIL cannot
    be interrupted by any in-process watchdog."""
    effective = deadline_seconds(seconds)

    def expire() -> None:
        sys.stderr.write(f"{hook}: evaluation exceeded {effective:g}s deadline; blocking (fail closed)\n")
        sys.stderr.flush()
        os._exit(2)

    timer = threading.Timer(effective, expire)
    timer.daemon = True
    timer.start()


# ---------------------------------------------------------------------------
# Private files
# ---------------------------------------------------------------------------

def _open_private(path: str, flags: int) -> int:
    """Open path with flags, creating it 0600 inside a 0700 directory, without
    following a symlink planted in its place."""
    os.makedirs(os.path.dirname(path), mode=0o700, exist_ok=True)
    return os.open(path, flags | os.O_CREAT | getattr(os, "O_NOFOLLOW", 0), 0o600)


def append_private(path: str, line: str) -> None:
    """Append line to a 0600 file without following a planted symlink."""
    fd = _open_private(str(path), os.O_WRONLY | os.O_APPEND)
    with os.fdopen(fd, "a") as f:
        f.write(line)


# ---------------------------------------------------------------------------
# Audit log
# ---------------------------------------------------------------------------

AUDIT_LOG_NAME = "hook-audit.jsonl"
AUDIT_LOG_MAX_BYTES = 10 * 1024 * 1024


def audit_log_path() -> str:
    """The audit log: under the project's git-ignored .claude/logs/, or the
    user's own ~/.claude/logs/ without a project directory. Never the working
    directory and never a shared location such as /tmp. Empty when neither is
    known."""
    base = os.environ.get("CLAUDE_PROJECT_DIR", "") or os.path.expanduser("~")
    if not os.path.isabs(base):
        return ""
    return os.path.join(base, ".claude", "logs", AUDIT_LOG_NAME)


def _lock(fd: int) -> None:
    """Hold an exclusive lock on fd (best effort)."""
    if fcntl is not None:
        fcntl.flock(fd, fcntl.LOCK_EX)
    elif msvcrt is not None:
        msvcrt.locking(fd, msvcrt.LK_LOCK, 1)


def _unlock(fd: int) -> None:
    if fcntl is not None:
        fcntl.flock(fd, fcntl.LOCK_UN)
    elif msvcrt is not None:
        os.lseek(fd, 0, os.SEEK_SET)
        msvcrt.locking(fd, msvcrt.LK_UNLCK, 1)


def audit_log(entry: dict) -> None:
    """Append entry, timestamped, as one JSON line to the audit log. Never
    raises: logging must not change a hook's decision.

    The file is created 0600 and rotated to <name>.1 once it exceeds
    AUDIT_LOG_MAX_BYTES. Rotation and append run under one lock on a
    <name>.lock sibling, so concurrent hooks rotate once and lose nothing.
    When the lock file cannot be opened (a planted symlink or directory in
    its place), the entry is still appended, unlocked and without rotation.
    Callers strip secrets from entry first."""
    path = audit_log_path()
    if not path:
        return
    try:
        line = json.dumps(dict(entry, timestamp=datetime.now(timezone.utc).isoformat()), default=str) + "\n"
    except (TypeError, ValueError):
        return
    try:
        lock_fd = _open_private(path + ".lock", os.O_RDWR)
    except OSError:
        try:
            append_private(path, line)
        except OSError:
            pass
        return
    try:
        try:
            _lock(lock_fd)
        except OSError:
            pass  # best effort: an unlocked append still beats no entry
        try:
            if os.lstat(path).st_size > AUDIT_LOG_MAX_BYTES:
                os.replace(path, path + ".1")
        except FileNotFoundError:
            pass
        append_private(path, line)
    except OSError:
        pass
    finally:
        try:
            _unlock(lock_fd)
        except OSError:
            pass
        os.close(lock_fd)


# ---------------------------------------------------------------------------
# Exec wrappers
# ---------------------------------------------------------------------------

class WrapperSpec(NamedTuple):
    value: frozenset         # options that take a separate value
    positional: str = ""     # "duration" / "one": a positional precedes the command
    runtime: bool = False    # appends arguments read at run time (xargs, parallel)
    script: frozenset = frozenset()   # options whose value is a shell script (flock -c)
    no_exec: frozenset = frozenset()  # options that make it NOT run the command (command -v)
    joins: bool = False      # runs its remaining arguments joined as a `sh -c` script (watch)
    # The first operand is a subcommand (tmux new-session), resolved by exact
    # name or alias, else as a prefix of a full name (`new-s`), as tmux does.
    # The mapped ones run a shell command, with their own grammar; any other
    # is judged as a plain command line of its words, and each operand as a
    # tmux command line (see _skip_tmux).
    subcommands: Optional[dict] = None
    # Options whose operands are a command for a running instance (screen -X
    # exec CMD); they override no_exec (`screen -x s -X exec CMD`).
    command: frozenset = frozenset()
    optional: frozenset = frozenset()  # options whose value is optional (screen -r [session])
    # tmux if-shell / confirm-before: operands that are tmux command lines,
    # "rest" after a leading shell script, or "all".
    commands: str = ""
    # Options that run the command when there is nothing to attach to
    # (screen -R: reattach, else create); they override no_exec anywhere in
    # the options (`screen -xRR s CMD`, `screen -r -R s CMD`).
    creates: frozenset = frozenset()


def _wrapper(value: str = "", positional: str = "", runtime: bool = False,
             script: str = "", no_exec: str = "", joins: bool = False,
             subcommands: Optional[dict] = None, command: str = "", optional: str = "",
             commands: str = "", creates: str = "") -> WrapperSpec:
    return WrapperSpec(frozenset(value.split()), positional, runtime,
                       frozenset(script.split()), frozenset(no_exec.split()), joins, subcommands,
                       frozenset(command.split()), frozenset(optional.split()), commands,
                       frozenset(creates.split()))


def _subcommands(*groups: tuple) -> dict:
    """Map every spelling (full name, then aliases) of each (spellings, spec)
    group."""
    return {name: spec for spellings, spec in groups for name in spellings.split()}


