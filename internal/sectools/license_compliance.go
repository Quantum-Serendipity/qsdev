// policyLicense is one license in the ScanCode license policy.
type policyLicense struct {
	spdx string // SPDX identifier, reported in scan findings
	key  string // ScanCode license key, which --license-policy matches on
}

// licensePolicyClass groups the licenses that share a policy outcome. The
// label and compliance_alert follow the ScanCode.io policy convention: an
// empty alert approves the license, "warning" asks for review and "error"
// prohibits it. The security-scan task fails on "error" only.
type licensePolicyClass struct {
	label    string
	alert    string
	licenses []policyLicense
}

